// TestXWINGUnmarshalPublicKey_IndependentCopy verifies that UnmarshalPublicKey
// returns independent copies (not aliases of the input buffer).
func TestXWINGUnmarshalPublicKey_IndependentCopy(t *testing.T) {
	pub, _, err := GenerateKeyPair()
	if err != nil {
		t.Fatalf("GenerateKeyPair: %v", err)
	}
	encoded, err := pub.MarshalBinary()
	if err != nil {
		t.Fatalf("MarshalBinary: %v", err)
	}

	recovered, err := UnmarshalPublicKey(encoded)
	if err != nil {
		t.Fatalf("UnmarshalPublicKey: %v", err)
	}

	// Mutate the original encoded buffer.
	for i := range encoded {
		encoded[i] = 0xff
	}

	// Recovered key should be unaffected.
	if !bytes.Equal(pub.MLKEMPub, recovered.MLKEMPub) {
		t.Error("MLKEMPub changed after mutating input buffer — not an independent copy")
	}
	if !bytes.Equal(pub.X25519Pub, recovered.X25519Pub) {
		t.Error("X25519Pub changed after mutating input buffer — not an independent copy")
	}
}

