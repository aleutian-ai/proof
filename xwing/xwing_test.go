// TestXWINGMarshalBinary_RoundTrip verifies that MarshalBinary and UnmarshalPublicKey
// are inverses of each other, and that the wire format is MLKEMPub ‖ X25519Pub.
func TestXWINGMarshalBinary_RoundTrip(t *testing.T) {
	pub, _, err := GenerateKeyPair()
	if err != nil {
		t.Fatalf("GenerateKeyPair: %v", err)
	}

	encoded, err := pub.MarshalBinary()
	if err != nil {
		t.Fatalf("MarshalBinary: %v", err)
	}
	if len(encoded) != 1216 {
		t.Fatalf("MarshalBinary: want 1216 bytes, got %d", len(encoded))
	}

	// Verify wire order: first 1184 bytes = MLKEMPub, last 32 bytes = X25519Pub
	if !bytes.Equal(encoded[:1184], pub.MLKEMPub) {
		t.Error("wire format: first 1184 bytes should be MLKEMPub")
	}
	if !bytes.Equal(encoded[1184:], pub.X25519Pub) {
		t.Error("wire format: last 32 bytes should be X25519Pub")
	}

	recovered, err := UnmarshalPublicKey(encoded)
	if err != nil {
		t.Fatalf("UnmarshalPublicKey: %v", err)
	}

	if !bytes.Equal(pub.X25519Pub, recovered.X25519Pub) {
		t.Errorf("X25519Pub mismatch after round-trip")
	}
	if !bytes.Equal(pub.MLKEMPub, recovered.MLKEMPub) {
		t.Errorf("MLKEMPub mismatch after round-trip")
	}
}

