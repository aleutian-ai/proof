// TestXWINGLabel verifies that label matches the IETF spec.
// Spec: XWingLabel = concat("\./", "/^\") = hex 5c2e2f2f5e5c (6 bytes).
func TestXWINGLabel(t *testing.T) {
	expected := []byte{0x5c, 0x2e, 0x2f, 0x2f, 0x5e, 0x5c}
	if !bytes.Equal(label, expected) {
		t.Errorf("label mismatch\n  got:  %x\n  want: %x", label, expected)
	}
	if len(label) != 6 {
		t.Errorf("label length: got %d, want 6", len(label))
	}
	// Verify ASCII interpretation: \.//^\
	// concat("\./", "/^\") = \. + / + / + ^ + \ = \.//^\
	ascii := "\\.//^\\"
	if string(label) != ascii {
		t.Errorf("label ASCII: got %q, want %q", string(label), ascii)
	}
}

// TestXWINGCombineFieldOrder verifies that combine uses the spec field order
// (draft-06: ss_M ‖ ss_X ‖ ct_X ‖ pk_X ‖ label — label LAST).
// This test independently computes SHA3-256 with known inputs and compares.
func TestXWINGCombineFieldOrder(t *testing.T) {
	// Use distinct 32-byte inputs so field-order bugs are detectable.
	ssM := bytes.Repeat([]byte{0x01}, 32)
	ssX := bytes.Repeat([]byte{0x02}, 32)
	ctX := bytes.Repeat([]byte{0x03}, 32)
	pkX := bytes.Repeat([]byte{0x04}, 32)

	// Compute expected SHA3-256 independently: ss_M ‖ ss_X ‖ ct_X ‖ pk_X ‖ label
	h := sha3.New256()
	h.Write(ssM)
	h.Write(ssX)
	h.Write(ctX)
	h.Write(pkX)
	h.Write(label) // label LAST
	expected := h.Sum(nil)

	got := combine(ssM, ssX, ctX, pkX)

	if !bytes.Equal(got[:], expected) {
		t.Errorf("combiner output mismatch (wrong field order?)\n  got:  %x\n  want: %x", got[:], expected)
	}

	// Verify that label-FIRST (draft-04 order) produces a DIFFERENT result.
	hWrong := sha3.New256()
	hWrong.Write(label) // label FIRST — wrong for draft-06
	hWrong.Write(ssM)
	hWrong.Write(ssX)
	hWrong.Write(ctX)
	hWrong.Write(pkX)
	wrongOrder := hWrong.Sum(nil)

	if bytes.Equal(got[:], wrongOrder) {
		t.Error("combiner output matches label-FIRST order; should use label-LAST (draft-06)")
	}
}

// TestXWINGKAT_Generate prints self-consistent KAT vectors to stdout.
// Run once with GENERATE_KAT=1 to populate testdata/xwing_kat.json.
// Not run during normal test execution.
//
// These are self-generated regression vectors, NOT IETF reference vectors.
// They verify internal consistency (encapsulate → decapsulate round-trip) and
// detect regressions in the combiner formula or wire format.
func TestXWINGKAT_Generate(t *testing.T) {
	if os.Getenv("GENERATE_KAT") == "" {
		t.Skip("set GENERATE_KAT=1 to generate test vectors")
	}

	type entry struct {
		Comment string `json:"_comment"`
		Seed    string `json:"seed"` // 32-byte XWING private key seed
		CT      string `json:"ct"`   // 1120-byte ciphertext (MLKEMCT ‖ X25519EPK)
		SS      string `json:"ss"`   // 32-byte expected shared secret
	}

	// Three fixed seeds built from sequential byte patterns.
	seeds := [][32]byte{
		func() [32]byte {
			var s [32]byte
			for i := range s {
				s[i] = 0x01 + byte(i)
			}
			return s
		}(),
		func() [32]byte {
			var s [32]byte
			for i := range s {
				s[i] = 0xa0 + byte(i)
			}
			return s
		}(),
		func() [32]byte {
			var s [32]byte
			for i := range s {
				s[i] = 0x51 + byte(i)
			}
			return s
		}(),
	}

	var entries []entry
	for i, seed := range seeds {
		func() {
			priv := PrivateKey{Seed: seed}
			defer priv.Zeroize()

			pub, err := priv.PublicKey()
			if err != nil {
				t.Fatalf("vector %d: derive public key: %v", i, err)
			}

			ct, ss, err := Encapsulate(pub)
			if err != nil {
				t.Fatalf("vector %d: encapsulate: %v", i, err)
			}
			defer ss.Zeroize()

			// Verify round-trip before recording.
			ss2, err := Decapsulate(ct, priv)
			if err != nil {
				t.Fatalf("vector %d: decapsulate verify: %v", i, err)
			}
			if ss != ss2 {
				t.Fatalf("vector %d: round-trip mismatch during generation", i)
			}

			// Serialize ciphertext in wire order: MLKEMCT ‖ X25519EPK
			ctBytes := make([]byte, 0, 1120)
			ctBytes = append(ctBytes, ct.MLKEMCT...)
			ctBytes = append(ctBytes, ct.X25519EPK...)

			entries = append(entries, entry{
				Comment: fmt.Sprintf("Vector %d — self-generated regression vector via TestXWINGKAT_Generate", i+1),
				Seed:    hex.EncodeToString(seed[:]),
				CT:      hex.EncodeToString(ctBytes),
				SS:      hex.EncodeToString(ss[:]),
			})
		}()
	}

	out, err := json.MarshalIndent(entries, "", "  ")
	if err != nil {
		t.Fatalf("marshal: %v", err)
	}

	if err := os.WriteFile("testdata/xwing_kat.json", out, 0644); err != nil {
		t.Fatalf("write testdata/xwing_kat.json: %v", err)
	}
	t.Logf("wrote %d vectors to testdata/xwing_kat.json", len(entries))
}

// xwingKATVector is one entry from testdata/xwing_kat.json.
//
// Vectors are self-generated by TestXWINGKAT_Generate and round-trip verified
// (encapsulate with matching pub, then decapsulate, assert shared secrets match).
// They serve as regression vectors for the combiner formula and decapsulation path.
//
// Seed is the 32-byte XWING private key seed. CT and SS were produced by a real
// Encapsulate call against the corresponding public key; since Decapsulate
// is deterministic, these values are stable across runs.
//
// To regenerate: GENERATE_KAT=1 go test ./xwing/... -run TestXWINGKAT_Generate -v
type xwingKATVector struct {
	Seed string `json:"seed"` // hex, 32 bytes — XWING private key seed
	CT   string `json:"ct"`   // hex, 1120 bytes — ciphertext (MLKEMCT ‖ X25519EPK)
	SS   string `json:"ss"`   // hex, 32 bytes — expected shared secret
}

// TestXWINGKAT verifies Decapsulate against self-generated regression vectors.
//
// REGRESSION ONLY. These vectors were produced by this implementation, so they
// detect change, not error: a deviation from the specification that predates
// them is baked into them and passes here. Conformance is TestSpecVectors
// (official vectors, checksum-authenticated) plus the differential test against
// circl at the repository root. Do not cite this test as evidence of
// conformance, and do not regenerate these vectors to make a failure go away.
// For each vector, reconstructs the private key from the 32-byte seed, then
// decapsulates the ciphertext and asserts the shared secret matches.
//
// A minimum of 2 vectors must be present and pass.
func TestXWINGKAT(t *testing.T) {
	data, err := os.ReadFile("testdata/xwing_kat.json")
	if err != nil {
		t.Fatalf("read testdata/xwing_kat.json: %v", err)
	}
	var vectors []xwingKATVector
	if err := json.Unmarshal(data, &vectors); err != nil {
		t.Fatalf("unmarshal KAT vectors: %v", err)
	}
	if len(vectors) < 2 {
		t.Fatalf("need at least 2 KAT vectors, got %d", len(vectors))
	}

	for i, vec := range vectors {
		vec := vec
		t.Run(fmt.Sprintf("vector_%d", i), func(t *testing.T) {
			seedBytes, err := hex.DecodeString(vec.Seed)
			if err != nil {
				t.Fatalf("decode seed: %v", err)
			}
			if len(seedBytes) != 32 {
				t.Fatalf("seed: want 32 bytes, got %d", len(seedBytes))
			}

			ctBytes, err := hex.DecodeString(vec.CT)
			if err != nil {
				t.Fatalf("decode ct: %v", err)
			}
			if len(ctBytes) != 1120 {
				t.Fatalf("ct: want 1120 bytes, got %d", len(ctBytes))
			}

			expectedSS, err := hex.DecodeString(vec.SS)
			if err != nil {
				t.Fatalf("decode ss: %v", err)
			}
			if len(expectedSS) != 32 {
				t.Fatalf("ss: want 32 bytes, got %d", len(expectedSS))
			}

			priv, err := NewPrivateKey(seedBytes)
			if err != nil {
				t.Fatalf("NewPrivateKey: %v", err)
			}
			defer priv.Zeroize()

			// Wire format: MLKEMCT (1088B) ‖ X25519EPK (32B)
			ct := Ciphertext{
				MLKEMCT:   ctBytes[:1088],
				X25519EPK: ctBytes[1088:],
			}

			ss, err := Decapsulate(ct, priv)
			if err != nil {
				t.Fatalf("Decapsulate: %v", err)
			}
			defer ss.Zeroize()

			if !bytes.Equal(ss[:], expectedSS) {
				t.Errorf("shared secret mismatch\n  got prefix:  %x...\n  want prefix: %x...", ss[:4], expectedSS[:4])
			}
		})
	}
}

// TestXWINGRoundTrip verifies that encapsulate followed by decapsulate produces
// matching shared secrets.
func TestXWINGRoundTrip(t *testing.T) {
	pub, priv, err := GenerateKeyPair()
	if err != nil {
		t.Fatalf("GenerateKeyPair: %v", err)
	}
	defer priv.Zeroize()

	ct, ss1, err := Encapsulate(pub)
	if err != nil {
		t.Fatalf("Encapsulate: %v", err)
	}
	defer ss1.Zeroize()

	ss2, err := Decapsulate(ct, priv)
	if err != nil {
		t.Fatalf("Decapsulate: %v", err)
	}
	defer ss2.Zeroize()

	if ss1 != ss2 {
		t.Errorf("shared secret mismatch: encapsulate prefix %x..., decapsulate prefix %x...", ss1[:4], ss2[:4])
	}
}

// TestXWINGWrongKey verifies that decapsulating with a different private key produces
// a different shared secret rather than an error. ML-KEM-768 uses implicit rejection
// (FIPS 203 §7.3): wrong-key decapsulation returns a pseudorandom value, not an error.
func TestXWINGWrongKey(t *testing.T) {
	pub1, _, err := GenerateKeyPair()
	if err != nil {
		t.Fatalf("GenerateKeyPair (1): %v", err)
	}

	_, priv2, err := GenerateKeyPair()
	if err != nil {
		t.Fatalf("GenerateKeyPair (2): %v", err)
	}
	defer priv2.Zeroize()

	ct, ss1, err := Encapsulate(pub1)
	if err != nil {
		t.Fatalf("Encapsulate: %v", err)
	}
	defer ss1.Zeroize()

	ss2, err := Decapsulate(ct, priv2)
	if err != nil {
		t.Fatalf("Decapsulate with wrong key returned unexpected error: %v", err)
	}
	defer ss2.Zeroize()

	if ss1 == ss2 {
		t.Error("wrong-key decapsulation produced the same shared secret (probability 2^-256)")
	}
}

