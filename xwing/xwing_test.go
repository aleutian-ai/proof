// TestXWINGStringer_Redaction verifies that String() and GoString() do not leak
// key material for PrivateKey and SharedSecret.
func TestXWINGStringer_Redaction(t *testing.T) {
	_, priv, err := GenerateKeyPair()
	if err != nil {
		t.Fatalf("GenerateKeyPair: %v", err)
	}
	defer priv.Zeroize()

	if s := priv.String(); s != "[REDACTED PrivateKey]" {
		t.Errorf("PrivateKey.String() = %q, want redacted", s)
	}
	if s := priv.GoString(); s != "[REDACTED PrivateKey]" {
		t.Errorf("PrivateKey.GoString() = %q, want redacted", s)
	}

	var ss SharedSecret
	ss[0] = 0x42
	if s := ss.String(); s != "[REDACTED SharedSecret]" {
		t.Errorf("SharedSecret.String() = %q, want redacted", s)
	}
	if s := ss.GoString(); s != "[REDACTED SharedSecret]" {
		t.Errorf("SharedSecret.GoString() = %q, want redacted", s)
	}

	// Verify fmt.Sprintf doesn't leak bytes.
	formatted := fmt.Sprintf("%v", priv)
	if formatted != "[REDACTED PrivateKey]" {
		t.Errorf("fmt.Sprintf(%%v, priv) = %q, want redacted", formatted)
	}
}

// TestXWINGExpandDecapsulationKey verifies that SHAKE256 expansion produces
// deterministic output from the same seed.
func TestXWINGExpandDecapsulationKey(t *testing.T) {
	var seed [32]byte
	for i := range seed {
		seed[i] = byte(i)
	}

	mlkemSeed1, x25519Priv1 := expandDecapsulationKey(seed)
	mlkemSeed2, x25519Priv2 := expandDecapsulationKey(seed)

	if mlkemSeed1 != mlkemSeed2 {
		t.Error("SHAKE256 expansion not deterministic for mlkemSeed")
	}
	if x25519Priv1 != x25519Priv2 {
		t.Error("SHAKE256 expansion not deterministic for x25519Priv")
	}

	// Different seeds must produce different output.
	var seed2 [32]byte
	seed2[0] = 0xff
	mlkemSeed3, x25519Priv3 := expandDecapsulationKey(seed2)

	if mlkemSeed1 == mlkemSeed3 {
		t.Error("different seeds produced same mlkemSeed")
	}
	if x25519Priv1 == x25519Priv3 {
		t.Error("different seeds produced same x25519Priv")
	}
}
