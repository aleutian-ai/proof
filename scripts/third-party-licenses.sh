# third-party-licenses.sh — build the THIRD_PARTY_LICENSES file each image ships.
#
# WHY
#   The images redistribute compiled third-party code: circl, golang.org/x/*,
#   bbolt, the MCP SDK and what it brings, and the Go runtime linked into every
#   Go binary. Their licences (BSD-3-Clause, MIT) require the copyright notice
#   and licence text to accompany a binary redistribution. The images carried
#   only this project's own /LICENSE.
#
# WHAT IT WRITES
#   licenses/proof/THIRD_PARTY_LICENSES        for the `proof` binary
#   licenses/proof-mcp/THIRD_PARTY_LICENSES    for the `proof-mcp` binary
#
#   Each file lists the modules that binary LINKS, then the licence files of
#   each. Not the module graph in go.mod: a module that is required but from
#   which no package is compiled in is not redistributed and is not listed.
#   The Dockerfile copies each file into its image, and its build stage refuses
#   a binary that links a module the file does not name.
#
# HOW
#   `go list -deps` on the command's package, for linux/amd64 and linux/arm64
#   (the two platforms published), in a workspace of the two modules, which is
#   how the Dockerfile builds. Licence text is read from the module cache and,
#   for the standard library, from GOROOT. No network (GOPROXY=off), no tools
#   beyond the Go toolchain.
#
# LIMITS
#   It reads the licence files at each module's root: LICENSE*, LICENCE*,
#   COPYING*, NOTICE*, PATENTS*. A module that keeps a separately licensed file
#   in a subdirectory without saying so at its root is not detected. It does
#   not judge whether a licence is acceptable; it fails only when a linked
#   module has no licence file at all.
#
# USAGE
#   ./scripts/third-party-licenses.sh            # rewrite both files
#   ./scripts/third-party-licenses.sh --check    # exit 1 if either is out of date

set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OWN_MODULE="github.com/aleutian-ai/proof"
OUT_DIR="$REPO_ROOT/licenses"
CHECK=0
for arg in "$@"; do
    case "$arg" in
        --check) CHECK=1 ;;
        -h|--help) sed -n '5,42p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
        *) echo "unknown argument $arg" >&2; exit 2 ;;
    esac
done

RED=$'\033[0;31m'; GREEN=$'\033[0;32m'; NC=$'\033[0m'
WORK="$(mktemp -d)"; trap 'rm -rf "$WORK"' EXIT

# The same workspace the Dockerfile makes: the two modules and nothing else.
# The repository's own go.work also lists the example modules, whose
# dependencies would raise versions the images do not build with.
# GOFLAGS is cleared so a -mod=vendor or -tags in the environment cannot change
# the answer.
go -C "$WORK" work init "$REPO_ROOT" "$REPO_ROOT/cmd/proof-mcp"
export GOWORK="$WORK/go.work" GOPROXY=off GOFLAGS= CGO_ENABLED=0 GOOS=linux

# linked_modules DIR: "path version dir" for every third-party module from
# which the command in DIR compiles at least one package, on either platform.
linked_modules() {
    local arch
    for arch in amd64 arm64; do
        GOARCH="$arch" go -C "$1" list -deps \
            -f '{{with .Module}}{{.Path}} {{.Version}} {{.Dir}}{{end}}' .
    done | grep -v "^$OWN_MODULE[/ ]" | LC_ALL=C sort -u
}

# license_files DIR: the licence files at a module's root, in a fixed order.
license_files() {
    local f
    for f in "$1"/*; do
        [[ -f "$f" ]] || continue
        case "$(basename "$f" | tr '[:lower:]' '[:upper:]')" in
            LICENSE*|LICENCE*|COPYING*|NOTICE*|PATENTS*) echo "$f" ;;
        esac
    done | LC_ALL=C sort
}

RULE="================================================================================"

# build NAME DIR OUT: write the notices file for one binary.
build() {
    local name="$1" dir="$2" out="$3" mods path version moddir files f
    mods="$(linked_modules "$dir")"
    [[ -n "$mods" ]] || { echo "${RED}no modules found for $name${NC}" >&2; return 1; }
    {
        echo "THIRD-PARTY LICENCES: $name"
        echo
        echo "The $name binary is licensed under Apache-2.0 (see /LICENSE). It links the"
        echo "third-party code listed here, each part under its own licence, reproduced"
        echo "below as its licence requires."
        echo
        echo "Generated by scripts/third-party-licenses.sh from the packages the binary"
        echo "links on linux/amd64 and linux/arm64. Do not edit; rerun the script."
        echo
        echo "$mods" | while read -r path version moddir; do
            echo "MODULE $path $version"
        done
        echo "MODULE go (the Go standard library and runtime)"
        echo "$mods" | while read -r path version moddir; do
            if [[ -z "$moddir" || ! -d "$moddir" ]]; then
                echo "${RED}$path $version is not in the module cache; run go mod download${NC}" >&2
                exit 1
            fi
            files="$(license_files "$moddir")"
            if [[ -z "$files" ]]; then
                echo "${RED}$path $version has no licence file at its root${NC}" >&2
                exit 1
            fi
            echo
            echo "$RULE"
            echo "$path $version"
            echo "$RULE"
            echo "$files" | while IFS= read -r f; do
                echo
                echo "---- $(basename "$f")"
                echo
                cat "$f"
            done
        done
        echo
        echo "$RULE"
        echo "go (the Go standard library and runtime)"
        echo "$RULE"
        for f in LICENSE PATENTS; do
            [[ -f "$(go env GOROOT)/$f" ]] || continue
            echo
            echo "---- $f"
            echo
            cat "$(go env GOROOT)/$f"
        done
    } >"$out"
}

FAILED=0
for target in "proof:$REPO_ROOT/cmd/proof" "proof-mcp:$REPO_ROOT/cmd/proof-mcp"; do
    name="${target%%:*}"; dir="${target#*:}"
    committed="$OUT_DIR/$name/THIRD_PARTY_LICENSES"
    fresh="$WORK/$name.licenses"
    build "$name" "$dir" "$fresh"
    count="$(grep -c '^MODULE ' "$fresh")"
    if [[ $CHECK -eq 1 ]]; then
        if [[ -f "$committed" ]] && cmp -s "$fresh" "$committed"; then
            echo "${GREEN}OK${NC}    licenses/$name/THIRD_PARTY_LICENSES ($count components)"
        else
            echo "${RED}STALE${NC} licenses/$name/THIRD_PARTY_LICENSES: rerun scripts/third-party-licenses.sh"
            { diff <(grep '^MODULE ' "$committed" 2>/dev/null || true) <(grep '^MODULE ' "$fresh") || true; } | head -20
            FAILED=$((FAILED+1))
        fi
    else
        mkdir -p "$OUT_DIR/$name"
        cp "$fresh" "$committed"
        echo "wrote licenses/$name/THIRD_PARTY_LICENSES ($count components)"
    fi
done

if [[ $FAILED -gt 0 ]]; then
    exit 1
fi
